export const SERVICE_SLUGS = services.map((s) => s.slug) as ServiceSlug[];

export type Lang = keyof LocalizedString;

export function isServiceSlug(value: string): value is ServiceSlug {
  return services.some((s) => s.slug === value);
}

export function getServiceBySlug(slug: string): ServiceContent | undefined {
  return services.find((s) => s.slug === slug);
}

export function getServiceIndex(slug: ServiceSlug) {
  return services.findIndex((s) => s.slug === slug);
}

export function serviceHref(slug: string) {
  return `/xizmatlar/${slug}`;
}

export function serviceImagePath(slug: string) {
  const s = getServiceBySlug(slug);
  return s?.image ?? `/images/services/${slug}.jpg`;
}

export function L(text: LocalizedString, lang: Lang): string {
  return text[lang] || text.uz;
}

/** Next 3 services after current (wraps around) for related links */
export function relatedServices(slug: ServiceSlug, count = 3): ServiceContent[] {
  const i = getServiceIndex(slug);
  if (i < 0) return services.slice(0, count);
  const out: ServiceContent[] = [];
  for (let n = 1; n <= services.length && out.length < count; n++) {
    out.push(services[(i + n) % services.length]);
  }
  return out;
}
